from __future__ import annotations

from collections.abc import Callable, Sequence
from pathlib import Path
from typing import TYPE_CHECKING, Literal

import numpy as np
import torch

from deepinv.datasets.base import ImageDataset
from deepinv.datasets.utils import resolve_root

if TYPE_CHECKING:
    import brainweb


class BrainWebPET(ImageDataset):
    r"""BrainWeb PET phantoms.

    This is a thin PyTorch wrapper around `casperdcl/brainweb
    <https://github.com/casperdcl/brainweb>`_. Each sample contains the PET
    emission map and the corresponding attenuation map generated by ``brainweb``.
    By default, volumes have shape ``(1, 127, 344, 344)`` at the Siemens Biograph
    mMR resolution.

    Spatial intensity variation is disabled by default by setting ``pet_noise``,
    ``t1_noise``, and ``t2_noise`` to zero. The noise amplitudes and smoothing
    scales can be configured independently, as can the PET activity class and
    output resolution. The absolute emission values alone do not determine
    simulation SNR; forward-model sensitivity and the Poisson noise gain also
    contribute.

    Passing ``lesion_diameters`` adds lesions with ``brainweb.add_lesions`` and
    includes a binary ``lesion_mask`` in the returned parameters.

    :param str, pathlib.Path, None root: Dataset directory. Defaults to the
        DeepInv cache.
    :param int, collections.abc.Sequence[int] subject_ids: Subjects to expose.
        Default is subject 4.
    :param bool download: Download missing subjects. Default is ``True``.
    :param collections.abc.Callable, None transform: Optional transform applied
        jointly to the channel-first emission, attenuation, and requested T1/T2
        tensors, as well as the lesion mask when present. The voxel size is
        unchanged.
    :param bool return_t1: If ``True``, include the T1 volume in the returned
        parameters. Defaults to ``False``.
    :param bool return_t2: If ``True``, include the T2 volume in the returned
        parameters. Defaults to ``False``.
    :param float pet_noise: Amplitude of multiplicative random intensity
        variation in the PET volume. ``0`` disables it, and ``1`` allows values
        from zero to twice the underlying intensity. Defaults to ``0``.
    :param float t1_noise: Amplitude of multiplicative random intensity
        variation in the T1 volume. Defaults to ``0``.
    :param float t2_noise: Amplitude of multiplicative random intensity
        variation in the T2 volume. Defaults to ``0``.
    :param float pet_sigma: Gaussian smoothing scale, in voxels, of the PET
        random intensity field. Defaults to ``0``.
    :param float t1_sigma: Gaussian smoothing scale, in voxels, of the T1
        random intensity field. Defaults to ``0``.
    :param float t2_sigma: Gaussian smoothing scale, in voxels, of the T2
        random intensity field. Defaults to ``0``.
    :param str outres: BrainWeb output resolution. Valid values are ``"mMR"``
        (default), ``"MR"``, and ``"brainweb"``.
    :param type[brainweb.Act], None pet_class: BrainWeb PET activity class. Defaults to
        ``brainweb.FDG``. Zero-argument callables used as activities are sampled
        when the dataset is initialized.
    :param list[float], None lesion_diameters: Lesion diameters in mm. Defaults
        to ``None``, which adds no lesions.
    :param list[float], None lesion_intensities: Peak lesion activities. Uses
        the BrainWeb defaults when ``None``.
    :param list[float], None lesion_blurs: Lesion Gaussian FWHMs in mm. Uses the
        BrainWeb defaults when ``None``.
    :param float, None lesion_threshold: Minimum activity on which to place a
        lesion. Uses the BrainWeb default when ``None``.
    :param int, None seed: Seed used by ``brainweb`` when adding lesions. A
        subject-specific seed is used for deterministic lesions by default.

    |sep|

    :Example:

    >>> import brainweb
    >>> import numpy as np
    >>> from deepinv.datasets import BrainWebPET
    >>> class RandomFDG(brainweb.FDG):
    ...     greyMatter = lambda: np.random.normal(128, 8)
    >>> dataset = BrainWebPET(
    ...     root="data/brainweb_pet",
    ...     pet_noise=0.5,
    ...     pet_sigma=2,
    ...     pet_class=RandomFDG,
    ...     lesion_diameters=[15, 7],
    ... )
    >>> emission, params = dataset[0]
    >>> emission.shape == params["attenuation"].shape
    True
    """

    def __init__(
        self,
        root: str | Path | None = None,
        subject_ids: int | Sequence[int] = 4,
        download: bool = True,
        transform: Callable | None = None,
        pet_class: type[brainweb.Act] | None = None,
        return_t1: bool = False,
        return_t2: bool = False,
        pet_noise: float = 0.0,
        t1_noise: float = 0.0,
        t2_noise: float = 0.0,
        pet_sigma: float = 0.0,
        t1_sigma: float = 0.0,
        t2_sigma: float = 0.0,
        outres: Literal["mMR", "MR", "brainweb"] = "mMR",
        lesion_diameters: list[float] | None = None,
        lesion_intensities: list[float] | None = None,
        lesion_blurs: list[float] | None = None,
        lesion_threshold: float | None = None,
        seed: int | None = 0,
    ) -> None:
        try:
            import brainweb
        except ImportError as error:  # pragma: no cover
            raise ImportError(
                "BrainWebPET requires brainweb. Install it with "
                "`pip install deepinv[dataset]`."
            ) from error

        pet_class = brainweb.FDG if pet_class is None else pet_class
        activities = {}
        for name in (*pet_class.attrs, "hot", "cold"):
            value = getattr(pet_class, name, None)
            if callable(value):
                activities[name] = value()
        if activities:
            pet_class = type(pet_class.__name__, (pet_class,), activities)

        self._brainweb = brainweb
        self.root = resolve_root(root, "BrainWebPET")
        self.transform = transform
        self.return_t1 = return_t1
        self.return_t2 = return_t2
        self.subject_ids = (
            (subject_ids,) if isinstance(subject_ids, int) else tuple(subject_ids)
        )
        available = {
            int(name[8:10]): (name, url) for name, url in brainweb.LINKS.items()
        }
        if not self.subject_ids or any(x not in available for x in self.subject_ids):
            raise ValueError(
                f"Incorrect subject_ids. Available values are {tuple(available)}."
            )

        self.files = []
        for subject in self.subject_ids:
            name, url = available[subject]
            path = self.root / name
            if download:
                path = Path(brainweb.get_file(name, url, cache_dir=self.root))
            elif not path.is_file():
                raise RuntimeError(
                    f"BrainWeb PET subject {subject} not found in {self.root}. "
                    "Set download=True."
                )
            self.files.append(path)

        self.brainweb_kwargs: dict[str, object] = {
            "petNoise": pet_noise,
            "t1Noise": t1_noise,
            "t2Noise": t2_noise,
            "petSigma": pet_sigma,
            "t1Sigma": t1_sigma,
            "t2Sigma": t2_sigma,
            "outres": outres,
        }
        self.brainweb_kwargs["PetClass"] = pet_class
        self.lesion_kwargs = (
            {
                "diam": lesion_diameters,
                "intensity": lesion_intensities,
                "blur": lesion_blurs,
                "thresh": lesion_threshold,
                "PetClass": pet_class,
            }
            if lesion_diameters
            else None
        )
        self.seed = seed

    def __len__(self) -> int:
        return len(self.files)

    def __getitem__(self, index: int):
        subject = self.subject_ids[index]
        volumes = self._brainweb.get_mmr_fromfile(
            str(self.files[index]), **self.brainweb_kwargs
        )
        emission = np.array(volumes["PET"], dtype=np.float32, copy=True)
        params = {
            "attenuation": torch.from_numpy(
                np.array(volumes["uMap"], dtype=np.float32, copy=True)
            ).unsqueeze(0),
            "voxel_size": torch.as_tensor(volumes["res"], dtype=torch.float32),
        }
        if self.return_t1:
            params["t1"] = torch.from_numpy(
                np.array(volumes["T1"], dtype=np.float32, copy=True)
            ).unsqueeze(0)
        if self.return_t2:
            params["t2"] = torch.from_numpy(
                np.array(volumes["T2"], dtype=np.float32, copy=True)
            ).unsqueeze(0)

        if self.lesion_kwargs is not None:
            original = emission.copy()
            if self.seed is not None:
                self._brainweb.seed(self.seed + subject)
            emission = self._brainweb.add_lesions(emission, **self.lesion_kwargs)
            params["lesion_mask"] = torch.from_numpy(emission != original).unsqueeze(0)

        emission = torch.from_numpy(emission).unsqueeze(0)
        if self.transform is not None:
            spatial_keys = [
                key
                for key in ("attenuation", "t1", "t2", "lesion_mask")
                if key in params
            ]
            spatial_volumes = self.transform(
                torch.cat([emission] + [params[key] for key in spatial_keys], dim=0)
            )
            emission = spatial_volumes[:1]
            for channel, key in enumerate(spatial_keys, start=1):
                params[key] = spatial_volumes[channel : channel + 1]

        return emission, params
