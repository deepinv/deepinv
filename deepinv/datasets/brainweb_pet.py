from __future__ import annotations

from collections.abc import Mapping, Sequence
from pathlib import Path

import numpy as np
import torch

from deepinv.datasets.base import ImageDataset
from deepinv.datasets.utils import resolve_root


class BrainWebPET(ImageDataset):
    r"""BrainWeb PET phantoms.

    This is a thin PyTorch wrapper around `casperdcl/brainweb
    <https://github.com/casperdcl/brainweb>`_. Each sample contains the PET
    emission map and the corresponding attenuation map generated by ``brainweb``.
    By default, volumes have shape ``(1, 127, 344, 344)`` at the Siemens Biograph
    mMR resolution.

    Spatial intensity variation is disabled by default by setting ``petNoise``,
    ``t1Noise``, and ``t2Noise`` to zero. Keyword arguments for
    ``brainweb.get_mmr_fromfile`` can override these defaults or select another
    tracer or resolution. For example, ``{"PetClass": brainweb.Amyloid}`` selects
    the amyloid preset. The absolute emission values alone do not determine
    simulation SNR; forward-model sensitivity and the Poisson noise gain also
    contribute.

    Passing ``lesion_kwargs`` adds lesions with ``brainweb.add_lesions`` and
    includes a binary ``lesion_mask`` in the returned parameters. The mapping is
    forwarded unchanged, so it can contain ``diam``, ``intensity``, ``blur``, or
    any other argument accepted upstream.

    :param str, pathlib.Path, None root: Dataset directory. Defaults to the
        DeepInv cache.
    :param int, sequence[int] subject_ids: Subjects to expose. Default is subject
        4.
    :param bool download: Download missing subjects. Default is ``True``.
    :param mapping, None brainweb_kwargs: Arguments forwarded to
        ``brainweb.get_mmr_fromfile``.
    :param mapping, None lesion_kwargs: Arguments forwarded to
        ``brainweb.add_lesions``. By default, no lesions are added.
    :param int, None seed: Seed used by ``brainweb`` when adding lesions. A
        subject-specific seed is used for deterministic lesions by default.

    |sep|

    :Example:

    >>> from deepinv.datasets import BrainWebPET
    >>> dataset = BrainWebPET(
    ...     root="data/brainweb_pet",
    ...     lesion_kwargs={"diam": [15, 7]},
    ... )
    >>> emission, params = dataset[0]
    >>> emission.shape == params["attenuation"].shape
    True
    """

    def __init__(
        self,
        root: str | Path | None = None,
        subject_ids: int | Sequence[int] = 4,
        download: bool = True,
        brainweb_kwargs: Mapping | None = None,
        lesion_kwargs: Mapping | None = None,
        seed: int | None = 0,
    ) -> None:
        try:
            import brainweb
        except ImportError as error:  # pragma: no cover
            raise ImportError(
                "BrainWebPET requires brainweb. Install it with "
                "`pip install deepinv[dataset]`."
            ) from error

        self._brainweb = brainweb
        self.root = resolve_root(root, "BrainWebPET")
        self.subject_ids = (
            (subject_ids,) if isinstance(subject_ids, int) else tuple(subject_ids)
        )
        available = {
            int(name[8:10]): (name, url) for name, url in brainweb.LINKS.items()
        }
        if not self.subject_ids or any(x not in available for x in self.subject_ids):
            raise ValueError(
                f"Incorrect subject_ids. Available values are {tuple(available)}."
            )

        self.files = []
        for subject in self.subject_ids:
            name, url = available[subject]
            path = self.root / name
            if download:
                path = Path(brainweb.get_file(name, url, cache_dir=self.root))
            elif not path.is_file():
                raise RuntimeError(
                    f"BrainWeb PET subject {subject} not found in {self.root}. "
                    "Set download=True."
                )
            self.files.append(path)

        self.brainweb_kwargs = {
            "petNoise": 0,
            "t1Noise": 0,
            "t2Noise": 0,
            **dict(brainweb_kwargs or {}),
        }
        self.lesion_kwargs = None if lesion_kwargs is None else dict(lesion_kwargs)
        self.seed = seed

    def __len__(self) -> int:
        return len(self.files)

    def __getitem__(self, index: int):
        subject = self.subject_ids[index]
        volumes = self._brainweb.get_mmr_fromfile(
            str(self.files[index]), **self.brainweb_kwargs
        )
        emission = np.array(volumes["PET"], dtype=np.float32, copy=True)
        params = {
            "attenuation": torch.from_numpy(
                np.array(volumes["uMap"], dtype=np.float32, copy=True)
            ).unsqueeze(0),
            "voxel_size": torch.as_tensor(volumes["res"], dtype=torch.float32),
        }

        if self.lesion_kwargs is not None:
            original = emission.copy()
            if self.seed is not None:
                self._brainweb.seed(self.seed + subject)
            emission = self._brainweb.add_lesions(emission, **self.lesion_kwargs)
            params["lesion_mask"] = torch.from_numpy(emission != original).unsqueeze(0)

        return torch.from_numpy(emission).unsqueeze(0), params
